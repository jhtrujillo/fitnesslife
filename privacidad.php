        <li><strong>Revocar la autorización</strong> o solicitar la supresión de sus datos de nuestras bases de datos cuando no medie un deber legal o contractual de conservarlos.</li>
        <li><strong>Acceder en forma gratuita</strong> a los datos personales que hayan sido objeto de tratamiento.</li>
      </ul>

